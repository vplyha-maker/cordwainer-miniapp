export const GLOSSARY_LETTERS = [
  'А', 'Б', 'В', 'Г', 'Д', 'З', 'И', 'К', 'Л', 'М', 'Н', 'О', 'П', 'Р', 'С', 'Т', 'У', 'Ф', 'Х', 'Ш', 'Ю', 'Я',
] as const

export function getTermsByLetter(letter: string): GlossaryTerm[] {
  return GLOSSARY_TERMS.filter((t) => t.letter === letter)
}

export function searchTerms(query: string, lang: 'ru' | 'uk' = 'ru'): GlossaryTerm[] {
  const q = query.trim().toLowerCase()
  if (!q) return GLOSSARY_TERMS
  return GLOSSARY_TERMS.filter((t) => {
    const term = (lang === 'uk' && t.termUk ? t.termUk : t.term).toLowerCase()
    const def = (lang === 'uk' && t.definitionUk ? t.definitionUk : t.definition).toLowerCase()
    return term.includes(q) || def.includes(q)
  })
}
