export function getIconicModelDossier(
  brandId: string,
  brandName: string,
  modelName: string,
  _lang: DossierLang = 'ru'
): IconicModelDossier {
  const cleanBrand = brandId.toLowerCase().trim()
  const exactKey = `${cleanBrand}|${modelName}`
  const rec = ICONIC_MODELS_DB[exactKey]

  if (rec) {
    return {
      modelName,
      debutYear: rec.year,
      creator: rec.creator,
      story: rec.story,
      culture: rec.culture,
      fact: rec.fact,
    }
  }

  // Поиск без учета регистра на случай мелких расхождений
  const lowerTarget = exactKey.toLowerCase()
  for (const [k, val] of Object.entries(ICONIC_MODELS_DB)) {
    if (k.toLowerCase() === lowerTarget) {
      return {
        modelName,
        debutYear: val.year,
        creator: val.creator,
        story: val.story,
        culture: val.culture,
        fact: val.fact,
      }
    }
  }

  return {
    modelName,
    debutYear: 'Archive',
    creator: brandName,
    story: `Знаковый архивный силуэт «${modelName}» из золотого фонда Дома ${brandName}.`,
    culture: `Постоянный участник мировых недель моды и частных коллекций ${brandName}.`,
    fact: `Создается по фирменным стандартам качества и материалов ателье ${brandName}.`,
  }
}

